/**
 * Source generated per plugin. Pure string building: no I/O, unit-tested on its own.
 *
 * The Claude Code engine scans a hooks module before it runs and refuses one whose state access it
 * cannot name, so atoms become literal `atom({ plugin, key })` consts behind a `switch`.
 */

import { CONFIG_CELL, type Plugin } from '../core/plugin'

const KEY = /^[A-Za-z_][A-Za-z0-9_-]*$/

const lit = (s: string) => JSON.stringify(s)

/** Keys `useState('…')` / `atom('…')` name in a source file, for atoms created lazily in components. */
export function scanStateKeys(source: string): string[] {
  const out = new Set<string>()
  for (const m of source.matchAll(/\b(?:useState|atom)\(\s*(['"])([A-Za-z][A-Za-z0-9_-]*)\1/g)) out.add(m[2]!)
  return [...out]
}

/** Every state key of a plugin: declared atoms, keys found in its sources, and the config cell. */
export function stateKeys(plugin: Plugin, scanned: Iterable<string> = []): string[] {
  const keys = new Set<string>([...plugin.atoms.map(a => a.key), ...scanned])
  if (plugin.config && Object.keys(plugin.config).length > 0) keys.add(CONFIG_CELL)
  for (const k of keys) if (!KEY.test(k)) throw new Error(`bifrost: state key "${k}" is not a plain identifier`)
  return [...keys].sort()
}

/** `virtual:bifrost/claude-state` for one plugin. */
export function claudeStateModule(name: string, keys: readonly string[]): string {
  const atoms = keys.map((k, i) => `const a${i} = atom({ plugin: ${lit(name)}, key: ${lit(k)} }, undefined)`)
  const reads = keys.map((k, i) => `    case ${lit(k)}:\n      return read($, a${i})`)
  const writes = keys.map((k, i) => `    case ${lit(k)}:\n      return update($, a${i}, fn)`)
  return [
    `import { atom, read, update } from 'claude-code'`,
    ...atoms,
    `export const CELLS = new Set([${keys.map(lit).join(', ')}])`,
    'export function readCell($, key) {',
    '  switch (key) {',
    ...reads,
    '  }',
    '  return Promise.resolve(undefined)',
    '}',
    'export function writeCell($, key, fn) {',
    '  switch (key) {',
    ...writes,
    '  }',
    '  return Promise.resolve(undefined)',
    '}',
    '',
  ].join('\n')
}

/** The hooks module entry: the engine wants `export const register = (on, options) => …`. */
export const claudeEntry = (pluginPath: string): string =>
  [
    `import plugin from ${lit(pluginPath)}`,
    `import { install } from '@gidragir/bifrost/claude'`,
    'export const register = (on, options) => install(on, options, plugin)',
    '',
  ].join('\n')

/** The agy server entry. */
export const agyEntry = (pluginPath: string, dev: boolean): string =>
  [`import plugin from ${lit(pluginPath)}`, `import { runAgy } from '@gidragir/bifrost/agy'`, `runAgy(plugin, { dev: ${dev} })`, ''].join(
    '\n',
  )

/** The manifest's `types` contract: the state keys the engine lets the module read and write. */
export function stateContract(name: string, keys: readonly string[]): string {
  const fields = keys.map(k => `${KEY.test(k) && !k.includes('-') ? k : lit(k)}: unknown`).join('; ')
  return [
    '// Generated by bifrost build: the state keys this plugin keeps in the engine.',
    "declare module 'claude-code' {",
    '  interface PluginState {',
    `    ${lit(name)}: { ${fields} }`,
    '  }',
    '}',
    '',
  ].join('\n')
}

/**
 * esbuild hoists top-level `const` to `var` in bundles; the engine accepts `register` only as a
 * const function, so the bundle is patched back.
 */
export function fixRegisterExport(bundle: string): string {
  return bundle.replace(/^var register = /m, 'const register = ')
}
